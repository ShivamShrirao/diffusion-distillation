"""Stock Qwen3-VL pairwise yes/no image judge (the DMDR reward)."""
from __future__ import annotations

from typing import List, Literal

import torch
from transformers import AutoProcessor, Qwen3VLForConditionalGeneration

from distributed import fsdp2_shard_frozen

PromptVer = Literal["aesthetic", "aesthetic_with_caption", "caption"]


class Qwen3ImageReward(torch.nn.Module):
    """
    Pairwise yes/no image reward built on the stock Qwen3-VL model.

    Always differentiable: gradients flow from input image tensors through the
    preprocessing pipeline, the vision encoder and the LM head, so this can be
    used as a reward on decoded student images (image -> VAE -> reward -> backprop to latents).
    """

    def __init__(
        self,
        device,
        model_name_or_path: str = "Qwen/Qwen3-VL-8B-Instruct",
        dtype: torch.dtype = torch.bfloat16,
        min_pixels: int = 4 * 28 * 28,
        max_pixels: int = 2048 * 28 * 28,
    ) -> None:
        super().__init__()
        self.device = torch.device(device)
        self.dtype = dtype
        self.model = Qwen3VLForConditionalGeneration.from_pretrained(model_name_or_path, dtype=dtype, attn_implementation="sdpa")
        self.model.to(self.device)
        self.processor = AutoProcessor.from_pretrained(model_name_or_path, min_pixels=min_pixels, max_pixels=max_pixels)
        self.yes_token_id, self.no_token_id = self.processor.tokenizer.encode("yes")[0], self.processor.tokenizer.encode("no")[0]

    @staticmethod
    def pair_message(sys_prompt: str):
        return [
            {
                "role": "user",
                "content": [
                    {"type": "image", "image": None},
                    {"type": "image", "image": None},
                    {"type": "text", "text": sys_prompt},
                ],
            }
        ]

    def get_message_relative_image_caption(self, image_caption: str):
        return self.pair_message(
            f"Both images were generated from the same prompt: {image_caption}\n"
            "Does image 1 match this prompt better than image 2? Please answer with 'yes' or 'no'."
        )

    def get_message_relative_image_aesthetic(self, image_caption: str):
        return self.pair_message(
            "You will act as a professional image quality evaluator.\n"
            "Your task is to be given two images, both of which are generated by the same prompt, and then evaluate which image has a better generation quality.\n"
            "The factors to be considered include: clarity, detail preservation, color accuracy, background quality, overall impression and aesthetic appeal\n"
            "Is image 1 better on these factors than image 2? Please answer with 'yes' or 'no'."
        )

    def get_message_relative_image_aesthetic_with_caption(self, image_caption: str):
        return self.pair_message(
            "You will act as a professional image quality evaluator.\n"
            f"Your task is to be given two images, both of which are generated by the same prompt: {image_caption}. Evaluate which image has a better generation quality.\n"
            "The factors to be considered include: clarity, detail preservation, color accuracy, background quality, overall impression and aesthetic appeal\n"
            "Is image 1 better on these factors than image 2? Please answer with 'yes' or 'no'."
        )

    def get_relative_distribution(
        self,
        prompts: List[str],
        images1: torch.Tensor,
        images2: torch.Tensor,
        prompt_ver: PromptVer = "aesthetic_with_caption",
    ) -> torch.Tensor:
        """(B, 2) softmax probabilities of answering ``yes`` / ``no`` to "is image 1 better than
        image 2". Images are (B, 3, H, W) in [0, 255]."""
        if images1.shape[0] != images2.shape[0]:
            raise ValueError("images1 and images2 must have the same batch size")
        get_message_method = getattr(self, f"get_message_relative_image_{prompt_ver}")
        texts = [
            self.processor.apply_chat_template(get_message_method(caption), tokenize=False, add_generation_prompt=True)
            for caption in prompts
        ]
        images = []
        for i in range(len(images1)):
            images.append(images1[i])
            images.append(images2[i])

        inputs = self.processor(text=texts, images=images, videos=None, padding=True, return_tensors="pt")
        inputs = {k: v.to(self.device) if torch.is_tensor(v) else v for k, v in inputs.items()}
        output_logits = self.model(**inputs, return_dict=True, use_cache=False)["logits"]

        attn = inputs["attention_mask"]
        indices = torch.arange(attn.shape[1], device=attn.device).unsqueeze(0)
        last_indices = (attn * indices).argmax(dim=1)
        last_token_logits = output_logits[torch.arange(output_logits.shape[0], device=output_logits.device), last_indices, :]
        probas = torch.nn.functional.softmax(last_token_logits.float(), dim=-1)
        return probas[:, [self.yes_token_id, self.no_token_id]]


def build_qwen_reward(args, accelerator, weight_dtype) -> Qwen3ImageReward:
    """Frozen judge, FSDP2-sharded over the student's mesh when FSDP is on."""
    reward_model = Qwen3ImageReward(device=accelerator.device, model_name_or_path=args.dmdr_judge, dtype=weight_dtype)
    reward_model.model.requires_grad_(False).eval()
    if args.gradient_checkpointing:
        reward_model.model.gradient_checkpointing_enable(gradient_checkpointing_kwargs={"use_reentrant": False})
    if args.use_fsdp and accelerator.num_processes > 1:
        fsdp2_shard_frozen(
            reward_model.model, accelerator, ["Qwen3VLTextDecoderLayer", "Qwen3VLVisionBlock"], param_dtype=weight_dtype
        )
    return reward_model
